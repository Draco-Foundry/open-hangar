// npm run rules: writes src/parser-rules-data.js from src/data/parser-rules.json and
// schema/parser-rules.schema.json.
//
// The JSON file is where the extension finds things on RSI's pages (src/parser-rules.js
// says how it's read). The extension's pages and its background worker load classic
// scripts, and the worker can't read a JSON file without a fetch, so
// src/parser-rules-data.js carries the rules and their schema as a script
// (self.OHParserRulesData). Run this after changing either file;
// test/parser-rules.test.js fails while they differ.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const RULES_FILE = 'src/data/parser-rules.json';
export const SCHEMA_FILE = 'schema/parser-rules.schema.json';
export const SCRIPT_FILE = 'src/parser-rules-data.js';

export async function rulesScript(rules, schema) {
  const text = `// Generated by scripts/parser-rules.mjs from ${RULES_FILE} and
// ${SCHEMA_FILE}: don't edit it here. Change the JSON files and run
// \`npm run rules\` (test/parser-rules.test.js checks they match). The parser rules
// and their schema for the extension's pages and the background worker, as
// self.OHParserRulesData (frozen), read by src/parser-rules.js.
(function (root) {
  const freeze = (v) => {
    if (v && typeof v === 'object') Object.values(Object.freeze(v)).forEach(freeze);
    return v;
  };
  const data = freeze({ schema: ${JSON.stringify(schema)}, rules: ${JSON.stringify(rules)} });
  root.OHParserRulesData = data;
  if (typeof module !== 'undefined' && module.exports) module.exports = data;
})(typeof self !== 'undefined' ? self : globalThis);
`;
  const options = (await prettier.resolveConfig(ROOT + SCRIPT_FILE)) || {};
  return prettier.format(text, { ...options, filepath: ROOT + SCRIPT_FILE });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const read = (f) => JSON.parse(readFileSync(ROOT + f, 'utf8'));
  writeFileSync(ROOT + SCRIPT_FILE, await rulesScript(read(RULES_FILE), read(SCHEMA_FILE)));
  console.log(`wrote ${SCRIPT_FILE} from ${RULES_FILE} and ${SCHEMA_FILE}`);
}
