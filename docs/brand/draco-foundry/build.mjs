/*
 * Build logo.svg (Draco Foundry): a machined gear with a glowing "D" in the
 * hub, meshed with a smaller gear, on a blueprint grid. Gear teeth are computed
 * so they come out exact. Then render the PNGs:
 *   node docs/brand/draco-foundry/build.mjs && node docs/brand/draco-foundry/render.mjs
 * Keep everything inside the centre circle: Discord crops server icons round.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const f = (n) => Number(n.toFixed(2));
const pt = (cx, cy, r, a) => `${f(cx + r * Math.cos(a))} ${f(cy + r * Math.sin(a))}`;

// Gear outline: `teeth` trapezoid teeth between rRoot and rOut, root arcs
// between them. `rot` turns the whole gear (radians).
function gearPath(cx, cy, rOut, rRoot, teeth, rot = 0) {
  const step = (2 * Math.PI) / teeth;
  const base = step * 0.54; // tooth width at the root
  const top = step * 0.3; // tooth width at the tip
  let d = '';
  for (let i = 0; i < teeth; i++) {
    const a = rot + i * step;
    const p = [
      pt(cx, cy, rRoot, a - base / 2),
      pt(cx, cy, rOut, a - top / 2),
      pt(cx, cy, rOut, a + top / 2),
      pt(cx, cy, rRoot, a + base / 2),
    ];
    d += `${i ? 'L' : 'M'}${p[0]} L${p[1]} A${rOut} ${rOut} 0 0 1 ${p[2]} L${p[3]} `;
    d += `A${rRoot} ${rRoot} 0 0 1 ${pt(cx, cy, rRoot, a + step - base / 2)} `;
  }
  return d + 'Z';
}
const circle = (cx, cy, r) =>
  `M${f(cx + r)} ${cy} A${r} ${r} 0 1 0 ${f(cx - r)} ${cy} A${r} ${r} 0 1 0 ${f(cx + r)} ${cy} Z`;

// Big gear
const G = { cx: 478, cy: 548, out: 318, root: 276, teeth: 14 };
// Small gear, meshed up and to the right at 45°
const dist = G.root + 112 - 6;
const S = {
  cx: f(G.cx + dist * Math.cos(-Math.PI / 4)),
  cy: f(G.cy + dist * Math.sin(-Math.PI / 4)),
  out: 124,
  root: 100,
  teeth: 8,
};
// Rotate so the big gear has a gap facing the small one and the small gear a
// tooth facing back: the teeth interleave.
const toSmall = -Math.PI / 4;
const gRot = toSmall + Math.PI / G.teeth;
const sRot = toSmall + Math.PI;

// Bolt holes around the big gear's inner ring
const bolts = Array.from({ length: 8 }, (_, i) => {
  const a = (i * Math.PI) / 4 + Math.PI / 8;
  return `<circle cx="${f(G.cx + 238 * Math.cos(a))}" cy="${f(G.cy + 238 * Math.sin(a))}" r="11" fill="#0c1016" stroke="#6b7685" stroke-width="3"/>`;
}).join('\n    ');

// Blueprint grid
const grid = [];
for (let x = 64; x < 1024; x += 64) {
  grid.push(`<line x1="${x}" y1="0" x2="${x}" y2="1024"/>`);
  grid.push(`<line x1="0" y1="${x}" x2="1024" y2="${x}"/>`);
}

// The D, centred on the big gear's hub: a bold slab D with a rounded bowl.
const D = (() => {
  const x = G.cx - 92,
    y = G.cy - 118,
    h = 236,
    w = 200,
    t = 50; // stroke thickness
  const r = h / 2;
  const ri = r - t;
  return (
    `M${x} ${y} H${x + w - r} A${r} ${r} 0 0 1 ${x + w - r} ${y + h} H${x} Z ` +
    `M${x + t} ${y + t} V${y + h - t} H${x + w - r} A${ri} ${ri} 0 0 0 ${x + w - r} ${y + t} Z`
  );
})();

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">
  <!-- Draco Foundry — generated by build.mjs; edit that, not this file. -->
  <defs>
    <radialGradient id="bg" cx="45%" cy="50%" r="75%">
      <stop offset="0" stop-color="#1b2230"/>
      <stop offset="0.7" stop-color="#0f141b"/>
      <stop offset="1" stop-color="#090c10"/>
    </radialGradient>
    <linearGradient id="steel" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#c3ccd8"/>
      <stop offset="0.45" stop-color="#7d8898"/>
      <stop offset="1" stop-color="#3a4350"/>
    </linearGradient>
    <linearGradient id="steelDark" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#8a95a5"/>
      <stop offset="1" stop-color="#2c333d"/>
    </linearGradient>
    <radialGradient id="recess" cx="50%" cy="45%" r="60%">
      <stop offset="0" stop-color="#1d2531"/>
      <stop offset="1" stop-color="#0b0f14"/>
    </radialGradient>
    <linearGradient id="ember" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#ffd27a"/>
      <stop offset="0.55" stop-color="#ff8a2a"/>
      <stop offset="1" stop-color="#e5531a"/>
    </linearGradient>
    <filter id="glow" x="-50%" y="-50%" width="200%" height="200%">
      <feGaussianBlur stdDeviation="16" result="b"/>
      <feMerge><feMergeNode in="b"/><feMergeNode in="SourceGraphic"/></feMerge>
    </filter>
    <filter id="shadow" x="-20%" y="-20%" width="140%" height="140%">
      <feDropShadow dx="0" dy="10" stdDeviation="14" flood-color="#000" flood-opacity="0.55"/>
    </filter>
  </defs>

  <rect width="1024" height="1024" fill="url(#bg)"/>
  <g stroke="#3b82c4" stroke-opacity="0.12" stroke-width="1.5">
    ${grid.join('\n    ')}
  </g>

  <!-- small gear (behind), star hub: Draco's eye -->
  <g filter="url(#shadow)">
    <path d="${gearPath(S.cx, S.cy, S.out, S.root, S.teeth, sRot)} ${circle(S.cx, S.cy, 34)}"
          fill="url(#steelDark)" fill-rule="evenodd" stroke="#1a2029" stroke-width="4"/>
    <circle cx="${S.cx}" cy="${S.cy}" r="70" fill="none" stroke="#1a2029" stroke-width="5" opacity="0.6"/>
  </g>
  <g transform="translate(${S.cx} ${S.cy})" filter="url(#glow)">
    <path d="M0 -26 L6 -6 L26 0 L6 6 L0 26 L-6 6 L-26 0 L-6 -6 Z" fill="#ffd27a"/>
  </g>

  <!-- big gear -->
  <g filter="url(#shadow)">
    <path d="${gearPath(G.cx, G.cy, G.out, G.root, G.teeth, gRot)}"
          fill="url(#steel)" stroke="#1a2029" stroke-width="5" stroke-linejoin="round"/>
  </g>
  <!-- bevel ring + recessed hub -->
  <circle cx="${G.cx}" cy="${G.cy}" r="262" fill="none" stroke="#e6ecf3" stroke-opacity="0.35" stroke-width="3"/>
  <circle cx="${G.cx}" cy="${G.cy}" r="206" fill="url(#recess)" stroke="#1a2029" stroke-width="6"/>
  <circle cx="${G.cx}" cy="${G.cy}" r="206" fill="none" stroke="#ff8a2a" stroke-opacity="0.35" stroke-width="3"/>
  <g>
    ${bolts}
  </g>

  <!-- glowing D -->
  <path d="${D}" fill="url(#ember)" fill-rule="evenodd" filter="url(#glow)"/>
</svg>
`;

fs.writeFileSync(path.join(HERE, 'logo.svg'), svg);
console.log('logo.svg written');
